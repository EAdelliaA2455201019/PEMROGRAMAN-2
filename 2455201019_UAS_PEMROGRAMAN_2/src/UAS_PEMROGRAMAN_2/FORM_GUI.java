     public void selectlistproduk(){
        konek.koneksi();
        try {
            
            String sql = "select*from listproduk";
            
            // MEMBUAT PREPARED STATEMENT MENGGUNAKAN KONEKSI YANG SEDANG AKTIF
            pst = konek.con.prepareStatement(sql);
            // MENJALANKAN QUERY DAN MENYIMPAN HASILNYA KE DALAM VARIABEL rs (RESULTSET)
            rs = pst.executeQuery(sql);
            
            /* MENGUBAH HASIL DARI DATABASE (rs) MENJADI FORMAT TABEL SECARA OTOMATIS
           DAN MENAMPILKANNYA PADA KOMPONEN tabelListProduk DI LAYAR */
            tabelListProduk.setModel(DbUtils.resultSetToTableModel(rs));
            
        } catch (Exception e){
            
            JOptionPane.showMessageDialog(null, e);
            
        }
        
    }
     
 private void selectriwayat() {
    DefaultTableModel model = new DefaultTableModel();
    model.addColumn("INVOICE");
    model.addColumn("ID USER");
    model.addColumn("SERVER");
    model.addColumn("EMAIL");
    model.addColumn("NO HP");
    model.addColumn("ID PRODUK");
    model.addColumn("HARGA");
    model.addColumn("TANGGAL");

    try {
        Connection con = konek.koneksi();
        
        // MEMBUAT OBJEK STATEMENT UNTUK MENGIRIM PERINTAH SQL
        Statement st = con.createStatement();
        // MENJALANKAN QUERY UNTUK MENGAMBIL SEMUA DATA DARI TABEL
        ResultSet rs = st.executeQuery("SELECT * FROM tabelriwayat");
        
        // MELAKUKAN LOOPING SELAMA DATA DI DALAM RESULTSET MASIH ADA
        while (rs.next()) {
            model.addRow(new Object[]{
                
                // rs.getString atau rs.getInt: CARA MENGAMBIL NILAI SESUAI TIPE DATA
                rs.getString("invoice"),  
                rs.getInt("id_user"),
                rs.getInt("server"),
                rs.getString("email"),
                rs.getString("no_hp"),
                rs.getInt("id_produk"),
                rs.getInt("harga"),
                rs.getTimestamp("tanggal")
            });
        }

        tabelRiwayat.setModel(model); 

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this, e.getMessage());
    }
}

