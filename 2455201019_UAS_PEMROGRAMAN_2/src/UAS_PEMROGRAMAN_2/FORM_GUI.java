           String harga = hargaProduk.getText();
   
           String sql = "UPDATE listproduk SET nama_produk = ?, harga = ? WHERE id_produk = ?";
           
           java.sql.PreparedStatement pst = konek.con.prepareStatement(sql);
           pst.setString(1, nama);
           pst.setString(2, harga);
           pst.setString(3, id);
           
